"""Self-contained reports — HTML match reports & teaming briefs + CSV/JSON.

Every HTML artifact is a single file with inline CSS and **no JavaScript, no CDN
dependency, no external asset** — it renders offline, air-gapped, and pastes
cleanly into an email or a data room. All values are HTML-escaped.

Exports:
  * ``match_report_html``  — ranked capital matches with per-match factor bars.
  * ``teaming_brief_html`` — a recommended team, coverage, and gap analysis.
  * ``matches_csv`` / ``matches_json`` — machine-readable match export.
  * ``team_json``          — machine-readable teaming recommendation.

SCOPE: business reporting only.
"""
